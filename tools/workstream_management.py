"""Offline repository metadata validation; evidence content still needs review."""
from __future__ import annotations

import fnmatch
import json
from pathlib import Path, PurePosixPath
import re
import subprocess

MARKER = "<!-- generated by tools/dev.py; do not edit -->"
SHA = re.compile(r"[0-9a-f]{40}\Z")
PINNED_URL = re.compile(r"https://github\.com/[^/]+/[^/]+/blob/[0-9a-f]{40}/[^?#]+\Z")
STATES = {"planned", "in_progress", "review_ready", "verified", "blocked", "changes_requested"}
TASK_FIELDS = {
    "format", "id", "title", "workstream", "state", "depends_on", "owner_role",
    "plan_ref", "scope_paths", "base_branch", "head_branch", "base_commit",
    "implementation_commit", "acceptance", "blockers", "handoff_ref",
    "verification_refs", "review_refs", "concurrency_group",
}
REQUIRED_TASK_FIELDS = TASK_FIELDS - {"review_refs", "concurrency_group"}
DOC_FIELDS = {"id", "path", "url", "kind", "workstream", "status", "owner_role", "related_tasks", "supersedes"}


def load_json(path: Path):
    def unique(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError(f"duplicate JSON key: {key}")
            result[key] = value
        return result
    return json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=unique)


def safe_path(root: Path, value: str, *, glob: bool = False) -> Path:
    if not isinstance(value, str) or not value or "\\" in value or ":" in value or value.startswith("/"):
        raise ValueError(f"unsafe path: {value}")
    if any(p in ("", ".", "..") for p in value.split("/")):
        raise ValueError(f"path escape or noncanonical path: {value}")
    if not glob and any(c in value for c in "*?["):
        raise ValueError(f"unexpected path glob: {value}")
    path = root / value
    for parent in (path, *path.parents):
        if parent.is_symlink() or (hasattr(parent, "is_junction") and parent.is_junction()):
            raise ValueError(f"linked path: {value}")
        if parent == root:
            break
    if not path.resolve().is_relative_to(root.resolve()):
        raise ValueError(f"path escape: {value}")
    return path


def _records(root: Path):
    catalog = load_json(safe_path(root, "docs/management/documents.json"))
    tasks_path = safe_path(root, "docs/management/tasks")
    tasks = [load_json(safe_path(root, p.relative_to(root).as_posix())) for p in sorted(tasks_path.glob("*.json"))]
    return catalog, tasks


def _cycles(records: dict, field: str) -> list[str]:
    errors, visiting, complete = [], set(), set()
    def walk(key):
        if key in visiting:
            errors.append(f"dependency cycle at {key}")
            return
        if key in complete or key not in records:
            return
        visiting.add(key)
        for dependency in records[key].get(field, []):
            walk(dependency)
        visiting.remove(key)
        complete.add(key)
    for key in records:
        walk(key)
    return errors


def render_board(root: Path) -> str:
    catalog, tasks = _records(root)
    docs = {d["id"]: d for d in catalog["documents"]}
    lines = [MARKER, "# Development board", "", "Task records are the sole state source. All downstream work is provisional until independent review.", "", "| Task | Stream | State | Dependencies | Implementation | Handoff | Limitations |", "| --- | --- | --- | --- | --- | --- | --- |"]
    for task in sorted(tasks, key=lambda t: t["id"]):
        ref = docs.get(task.get("handoff_ref"), {})
        target = "../" + ref["path"].removeprefix("docs/") if "path" in ref else ref.get("url")
        handoff = f"[report]({target})" if target else "pending"
        limitations = list(task.get("blockers", []))
        for review_id in task.get("review_refs", []):
            review_doc = docs.get(review_id, {})
            if "path" in review_doc:
                review = load_json(safe_path(root, review_doc["path"]))
                limitations.extend(review.get("limitations", []))
        cells = [f"[{task['id']}](tasks/{task['id']}.json)", task["workstream"], task["state"], ", ".join(task["depends_on"]) or "—", task.get("implementation_commit") or "pending", handoff, "; ".join(limitations) or "—"]
        lines.append("| " + " | ".join(str(c).replace("|", "\\|").replace("\n", " ") for c in cells) + " |")
    return "\n".join(lines) + "\n"


def validate(root: Path) -> list[str]:
    errors = []
    try:
        catalog, tasks = _records(root)
        if not isinstance(catalog, dict) or catalog.get("format") != "irisx.documents.v1":
            raise ValueError("invalid documents format")
        if set(catalog) - {"format", "documents", "legacy_indexes", "managed_scopes", "baseline_commit"}:
            errors.append("unknown documents catalog field")
        if catalog.get("baseline_commit") is not None and (not isinstance(catalog["baseline_commit"], str) or not SHA.fullmatch(catalog["baseline_commit"])):
            errors.append("invalid baseline commit SHA")
        docs = {}
        paths = {}
        for doc in catalog["documents"]:
            if not isinstance(doc, dict) or set(doc) - DOC_FIELDS or not (DOC_FIELDS - {"path", "url"}) <= set(doc):
                raise ValueError("invalid document fields")
            key = doc["id"]
            for field in ("id", "owner_role"):
                if not isinstance(doc[field], str) or not doc[field].strip():
                    raise ValueError(f"invalid document string: {field}")
            if key in docs:
                errors.append(f"duplicate document ID: {key}")
            docs[key] = doc
            if ("path" in doc) == ("url" in doc):
                errors.append(f"document {key}: exactly one path or url required")
            if doc["kind"] not in {"guide", "plan", "decision", "reference", "evidence", "prompt"} or doc["status"] not in {"draft", "active", "superseded", "historical"}:
                errors.append(f"invalid document kind/status: {key}")
            if doc["workstream"] not in {"core", "arc-agi-2", "line-b", "all"}:
                errors.append(f"invalid document workstream: {key}")
            if "path" in doc:
                path = safe_path(root, doc["path"])
                if not path.is_file():
                    errors.append(f"missing document: {doc['path']}")
                if doc["path"].casefold() in paths:
                    errors.append(f"duplicate document path: {doc['path']}")
                paths[doc["path"].casefold()] = key
            if "url" in doc and not PINNED_URL.fullmatch(doc["url"]):
                errors.append(f"unpinned source URL: {key}")
            for field in ("related_tasks", "supersedes"):
                if not isinstance(doc[field], list) or any(not isinstance(x, str) for x in doc[field]):
                    raise ValueError(f"invalid document refs: {key}.{field}")
        legacy_ids = set(docs)
        for index in catalog.get("legacy_indexes", []):
            if set(index) != {"id", "url", "scope"} or not PINNED_URL.fullmatch(index["url"]):
                errors.append("invalid pinned legacy index")
            if index["id"] in legacy_ids:
                errors.append(f"duplicate legacy ID: {index['id']}")
            legacy_ids.add(index["id"])
            if not isinstance(index["scope"], list):
                raise ValueError("invalid legacy scope list")
            for pattern in index["scope"]:
                safe_path(root, pattern, glob=True)
        task_index = {}
        for task in tasks:
            if not isinstance(task, dict) or set(task) - TASK_FIELDS or not REQUIRED_TASK_FIELDS <= set(task):
                raise ValueError("unknown or missing task fields (executable commands forbidden)")
            key = task["id"]
            for field in ("id", "title", "owner_role", "base_branch", "head_branch", "plan_ref"):
                if not isinstance(task[field], str) or not task[field].strip():
                    raise ValueError(f"invalid task string: {field}")
            if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_-]*", key) or not (root / f"docs/management/tasks/{key}.json").is_file():
                errors.append(f"task ID/filename mismatch: {key}")
            if key in task_index:
                errors.append(f"duplicate task ID: {key}")
            task_index[key] = task
            if task["format"] != "irisx.task.v1" or task["state"] not in STATES:
                errors.append(f"invalid task state/format: {key}")
            if task["workstream"] not in {"core", "arc-agi-2", "line-b"}:
                errors.append(f"invalid task workstream: {key}")
            for field in ("depends_on", "scope_paths", "acceptance", "blockers", "verification_refs", "review_refs"):
                if not isinstance(task.get(field, []), list) or any(not isinstance(x, str) for x in task.get(field, [])):
                    raise ValueError(f"invalid task list: {key}.{field}")
            if not task["scope_paths"] or not task["acceptance"]:
                errors.append(f"empty scope/acceptance: {key}")
            for scope in task["scope_paths"]:
                safe_path(root, scope, glob=True)
                if re.split(r"[*?[]", scope)[0].rstrip("/") == "":
                    errors.append(f"scope requires an explicit path prefix: {key}: {scope}")
            for field in ("base_commit", "implementation_commit"):
                if task[field] is not None and (not isinstance(task[field], str) or not SHA.fullmatch(task[field])):
                    errors.append(f"invalid commit SHA: {key}.{field}")
                elif task[field] is not None and (root / ".git").exists():
                    check = subprocess.run(["git", "cat-file", "-t", task[field]], cwd=root, capture_output=True, text=True)
                    if check.returncode or check.stdout.strip() != "commit":
                        errors.append(f"missing Git commit object: {key}.{field}")
            refs = [task["plan_ref"], *task["verification_refs"], *task.get("review_refs", [])]
            if task["handoff_ref"] is not None:
                refs.append(task["handoff_ref"])
            for ref in refs:
                if ref not in docs:
                    errors.append(f"dangling document reference: {key} -> {ref}")
            plan = docs.get(task["plan_ref"], {})
            text = None
            if "path" in plan:
                plan_path = safe_path(root, plan["path"])
                if plan_path.is_file():
                    text = plan_path.read_text(encoding="utf-8")
            elif "url" in plan and PINNED_URL.fullmatch(plan["url"]):
                commit, path = plan["url"].split("/blob/", 1)[1].split("/", 1)
                fetched = subprocess.run(["git", "show", f"{commit}:{path}"], cwd=root, capture_output=True, text=True, encoding="utf-8")
                if fetched.returncode == 0:
                    text = fetched.stdout
            if text is None:
                errors.append(f"cannot validate plan/check references locally: {key}")
            else:
                for check in task["acceptance"]:
                    if not re.search(r"(?<![\w-])" + re.escape(check) + r"(?![\w-])", text):
                        errors.append(f"dangling check reference: {key} -> {check}")
            if task["state"] in {"review_ready", "verified"} and (task["implementation_commit"] is None or task["handoff_ref"] is None):
                errors.append(f"missing commit/handoff for {task['state']}: {key}")
            if task["state"] == "blocked" and not task["blockers"]:
                errors.append(f"blocked task lacks blockers: {key}")
            if task["state"] == "verified":
                valid_review = False
                for ref in task.get("review_refs", []):
                    doc = docs.get(ref, {})
                    if "path" not in doc:
                        continue
                    report = load_json(safe_path(root, doc["path"]))
                    limitations = report.get("limitations")
                    source = report.get("source")
                    if (report.get("format") == "irisx.review.v1" and report.get("target_commit") == task["implementation_commit"] and report.get("reviewer_role") == "independent" and report.get("outcome") in {"verified", "verified_with_limits"} and isinstance(source, str) and source.strip() and isinstance(limitations, list) and all(isinstance(x, str) for x in limitations) and (report["outcome"] != "verified_with_limits" or limitations)):
                        valid_review = True
                if not valid_review:
                    errors.append(f"verified lacks commit-bound independent review: {key}")
        for doc in docs.values():
            for ref in doc["related_tasks"]:
                if ref not in task_index:
                    errors.append(f"dangling task reference: {doc['id']} -> {ref}")
            for ref in doc["supersedes"]:
                if ref not in docs:
                    errors.append(f"dangling supersedes reference: {doc['id']} -> {ref}")
        for task in tasks:
            for ref in task["depends_on"]:
                if ref not in task_index:
                    errors.append(f"dangling dependency: {task['id']} -> {ref}")
        errors.extend(_cycles(task_index, "depends_on"))
        errors.extend(_cycles(docs, "supersedes"))
        for path in ("README.md", "AGENTS.md", "PRODUCT_THESIS.md", "docs/README.md", "docs/product/README.md", "docs/development/README.md", "docs/development/operating-model.md", "docs/development/data-and-execution-policy.md", "docs/workstreams/README.md", "tests/README.md"):
            if (root / path).is_file() and path.casefold() not in paths:
                errors.append(f"missing required document catalog entry: {path}")
        for i, task in enumerate(tasks):
            group = task.get("concurrency_group")
            if not group or task["state"] != "in_progress":
                continue
            for other in tasks[i + 1:]:
                if other.get("concurrency_group") == group and other["state"] == "in_progress":
                    for first in task["scope_paths"]:
                        for second in other["scope_paths"]:
                            first_prefix, second_prefix = re.split(r"[*?[]", first)[0], re.split(r"[*?[]", second)[0]
                            if first == second or first_prefix.startswith(second_prefix) or second_prefix.startswith(first_prefix):
                                errors.append(f"concurrent scope conflict: {task['id']} / {other['id']}: {first} / {second}")
        for pattern in catalog.get("managed_scopes", []):
            safe_path(root, pattern, glob=True)
            prefix = re.split(r"[*?[]", pattern)[0].rstrip("/")
            if not prefix:
                raise ValueError("managed scope requires an explicit path prefix")
            start = safe_path(root, prefix) if prefix else root
            if start.exists():
                candidates = [start] if start.is_file() else start.rglob("*")
                for candidate in candidates:
                    relative = candidate.relative_to(root).as_posix()
                    if candidate.suffix == ".md" and fnmatch.fnmatchcase(relative, pattern):
                        safe_path(root, relative)
                        if relative.casefold() not in paths:
                            errors.append(f"unregistered active document: {relative}")
        # Fixed research references are structural/local checks, never remote attestation.
        if (root / "docs/workstreams/arc-agi-2/RESEARCH.md").is_file():
            if "docs/workstreams/arc-agi-2/research.md" not in paths:
                errors.append("missing ARC research entry")
            research_text = (root / "docs/workstreams/arc-agi-2/RESEARCH.md").read_text(encoding="utf-8")
            for url in re.findall(r"https://github\.com/[^\s)]+/blob/[^\s)]+", research_text):
                if not PINNED_URL.fullmatch(url) or not any(d.get("url") == url for d in docs.values()):
                    errors.append(f"dangling or unpinned research source: {url}")
        for doc in docs.values():
            url = doc.get("url")
            if url and PINNED_URL.fullmatch(url) and (root / ".git").exists():
                commit, path = url.split("/blob/", 1)[1].split("/", 1)
                safe_path(root, path)
                check = subprocess.run(["git", "cat-file", "-e", f"{commit}:{path}"], cwd=root, capture_output=True)
                if check.returncode:
                    errors.append(f"missing local pinned source object: {doc['id']}")
        baseline = catalog.get("baseline_commit")
        if baseline and SHA.fullmatch(baseline) and (root / ".git").exists():
            diff = subprocess.run(["git", "diff", "--name-only", baseline, "--", "*.md"], cwd=root, capture_output=True, text=True)
            if diff.returncode:
                errors.append("cannot inspect changed active documents")
            else:
                for path in diff.stdout.splitlines():
                    if (root / path).exists() and path.casefold() not in paths:
                        errors.append(f"unregistered modified active document: {path}")
            untracked = subprocess.run(["git", "ls-files", "--others", "--exclude-standard", "--", "*.md"], cwd=root, capture_output=True, text=True)
            for path in untracked.stdout.splitlines():
                if path.casefold() not in paths:
                    errors.append(f"unregistered new active document: {path}")
        board = safe_path(root, "docs/management/BOARD.md")
        if not board.is_file() or board.read_text(encoding="utf-8") != render_board(root):
            errors.append("stale or missing generated BOARD")
    except (ValueError, OSError, KeyError, TypeError, AttributeError) as exc:
        errors.append(str(exc))
    return errors
